// import ด้วยนามสกุล .ts เพื่อให้ `node --test` รันได้ตรง
import { daysUntil, toBangkokParts, toDueAt } from "./dates.ts";
import type { Lang } from "./i18n.ts";
import { t } from "./messages.ts";

export type ExamType = "midterm" | "final" | "other";
export const EXAM_TYPES: ExamType[] = ["midterm", "final", "other"];
export const EXAM_TYPE_LABEL: Record<ExamType, string> = {
  midterm: "สอบกลางภาค",
  final: "สอบปลายภาค",
  other: "สอบอื่น ๆ",
};

export function examTypeLabel(type: ExamType, lang: Lang = "th"): string {
  return t(lang, `examType.${type}`);
}

export function isExamType(v: unknown): v is ExamType {
  return v === "midterm" || v === "final" || v === "other";
}

// จำนวนวันที่ถือว่า "ใกล้ถึง" (แถบบนหน้างาน)
export const UPCOMING_EXAM_DAYS = 14;

const TIME_RE = /^([01]\d|2[0-3]):[0-5]\d$/;

// วัน + เวลาเริ่ม/จบ (เวลาไทย) → ค่าที่เก็บในตาราง events
// ไม่รู้วัน = starts_at null; รู้แค่วัน = 00:00 ของวันนั้น (has_time false)
// เวลาจบเก็บเฉพาะเมื่อมีเวลาเริ่ม และจบหลังเริ่ม
export function buildExamTimes(
  date: string | null,
  start: string | null,
  end: string | null,
  lang: Lang = "th",
):
  | { ok: true; starts_at: string | null; ends_at: string | null; has_time: boolean }
  | { ok: false; error: string } {
  if (!date) {
    if (start || end) return { ok: false, error: t(lang, "examTime.needDate") };
    return { ok: true, starts_at: null, ends_at: null, has_time: false };
  }
  if (start && !TIME_RE.test(start)) return { ok: false, error: t(lang, "examTime.badStart") };
  if (end && !TIME_RE.test(end)) return { ok: false, error: t(lang, "examTime.badEnd") };
  if (end && !start) return { ok: false, error: t(lang, "examTime.endNeedsStart") };
  if (start && end && end <= start) return { ok: false, error: t(lang, "examTime.endAfterStart") };

  const startsAt = toDueAt(date, start || "00:00");
  if (!startsAt) return { ok: false, error: t(lang, "examTime.badDate") };
  return {
    ok: true,
    starts_at: startsAt,
    ends_at: start && end ? toDueAt(date, end) : null,
    has_time: Boolean(start),
  };
}

// ช่วงเวลาสอบ เช่น "09:00–12:00 น." หรือ "09:00 น." (null = ไม่รู้เวลา)
export function formatExamTime(e: {
  starts_at: string | null;
  ends_at: string | null;
  has_time: boolean;
}, lang: Lang = "th"): string | null {
  if (!e.starts_at || !e.has_time) return null;
  const start = toBangkokParts(e.starts_at).time;
  const end = e.ends_at ? toBangkokParts(e.ends_at).time : null;
  return `${start}${end ? `–${end}` : ""}${lang === "th" ? " น." : ""}`;
}

// "วันนี้" / "พรุ่งนี้" / "อีก 5 วัน" / "ผ่านไปแล้ว"
export function countdownLabel(days: number, lang: Lang = "th"): string {
  if (days < 0) return t(lang, "countdown.past");
  if (days === 0) return t(lang, "countdown.today");
  if (days === 1) return t(lang, "countdown.tomorrow");
  return t(lang, "countdown.days", { n: days });
}

// สอบที่ยังไม่ถึง (รวมวันนี้) ภายใน `days` วัน เรียงตามวัน
export function upcomingExams<T extends { starts_at: string | null }>(
  exams: T[],
  now: Date = new Date(),
  days: number = UPCOMING_EXAM_DAYS,
): (T & { daysLeft: number })[] {
  return exams
    .filter((e): e is T & { starts_at: string } => Boolean(e.starts_at))
    .map((e) => ({ ...e, daysLeft: daysUntil(e.starts_at, now) }))
    .filter((e) => e.daysLeft >= 0 && e.daysLeft <= days)
    .sort((a, b) => a.starts_at.localeCompare(b.starts_at));
}

// ─── เวลาสอบชนกัน ───

export type TimedExam = {
  starts_at: string | null;
  ends_at: string | null;
  has_time: boolean;
};

// ชนกัน = ช่วงเวลาทับกันจริง (ต้องรู้เวลาเริ่มทั้งคู่)
// 08:00–11:00 กับ 11:00–13:00 ไม่ชน (จบพอดีตอนอีกวิชาเริ่ม)
// เริ่มเวลาเดียวกัน = ชน; ไม่รู้เวลาจบ = ถือเป็นจุดเวลาเริ่ม (ชนเมื่ออยู่ในช่วงของอีกวิชา)
export function examsOverlap(a: TimedExam, b: TimedExam): boolean {
  if (!a.starts_at || !b.starts_at || !a.has_time || !b.has_time) return false;
  const aS = Date.parse(a.starts_at);
  const bS = Date.parse(b.starts_at);
  const aE = a.ends_at ? Date.parse(a.ends_at) : aS;
  const bE = b.ends_at ? Date.parse(b.ends_at) : bS;
  if (aS === bS) return true;
  return aS < bE && bS < aE;
}

// รายการที่ชนกับแต่ละตัว (key = ลำดับใน array)
export function findOverlaps<T extends TimedExam>(exams: T[]): Map<number, T[]> {
  const out = new Map<number, T[]>();
  exams.forEach((a, i) => {
    const hits = exams.filter((b, j) => j !== i && examsOverlap(a, b));
    if (hits.length) out.set(i, hits);
  });
  return out;
}
